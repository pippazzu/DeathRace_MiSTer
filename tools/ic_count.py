"""IC-type count for the traced board, generated from the chip list in rtl/deathrac_board.v.

The chip list (between the "chip list" markers) is kept by hand, one IC per line:
    // REF   TYPE   note
This script writes the IC-type count block below it and checks the list against
the chip declarations in netlist/*.net, the pins in deathrace.overrides and the generated rtl/deathrac_netlist.v.

    python tools/ic_count.py          rewrite the count block
    python tools/ic_count.py --check  exit 1 if the block is stale or a check fails
"""
import collections, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BOARD = ROOT/'rtl/deathrac_board.v'
LIST_BEGIN = '// ---- chip list: begin ----'
LIST_END = '// ---- chip list: end ----'
COUNT_BEGIN = '// ---- IC-type count (generated by tools/ic_count.py; do not edit): begin ----'
COUNT_END = '// ---- IC-type count: end ----'
# Board locations: Chicago Coin grid (C12) or, for the Death Race-only gates, Exidy (13R).
REF = r'(?:[A-Z]\d{1,2}|\d{1,2}[A-Z])'
DUPLICATE = 'duplicate designator'

def ref_key(ref):
    m = re.fullmatch(r'([A-Z])(\d+)', ref)
    return (0, m[1], int(m[2])) if m else (1, ref[-1], int(ref[:-1]))

def cell_type(t):
    return {'JK112A': '74112', 'JK112B': '74112'}.get(t, t)

def fail(errors, msg): errors.append(msg)

def read_list(text, errors):
    try:
        body = text.split(LIST_BEGIN, 1)[1].split(LIST_END, 1)[0]
    except IndexError:
        raise SystemExit(f'ERROR: chip list markers not found in {BOARD}')
    chips = []
    for line in body.splitlines():
        line = line.strip()
        if not line: continue
        m = re.fullmatch(rf'//\s+({REF})\s+(\S+)(?:\s+(.*))?', line)
        if m: chips.append((m[1], m[2], (m[3] or '').strip()))
        elif line.startswith('//') and not re.match(rf'//\s+{REF}\b', line): continue  # prose
        else: fail(errors, f'cannot parse chip list line: {line!r}')
    return chips

def netlist_refs():
    """(package, type) for every cell or gate in the sheets."""
    found = collections.defaultdict(set)
    for f in sorted((ROOT/'netlist').glob('sheet*.net')):
        for line in f.read_text().splitlines():
            line = line.split('#')[0].split()
            if line and line[0] in ('chip', 'prom'): found[line[1]].add(cell_type(line[2]))
    return found

def check(chips, text, errors):
    refs = [r for r, _, _ in chips]
    if [ref_key(r) for r in refs] != sorted(ref_key(r) for r in refs):
        fail(errors, 'chip list is not sorted')
    listed = collections.defaultdict(set)
    for r, t, note in chips:
        if t in listed[r]:
            fail(errors, f'{r} {t} listed twice')
        listed[r].add(t)
    for r, n in collections.Counter(refs).items():
        if n > 1 and not any(DUPLICATE in note for x, _, note in chips if x == r):
            fail(errors, f'{r} listed {n} times without "{DUPLICATE}" in a note')
    traced = netlist_refs()
    for r, types in sorted(traced.items(), key=lambda x: ref_key(x[0])):
        if r not in listed: fail(errors, f'{r} ({"/".join(sorted(types))}) is in netlist/ but not in the chip list')
        elif types != listed[r]:
            fail(errors, f'{r}: netlist has {"/".join(sorted(types))}, chip list says {"/".join(sorted(listed[r]))}')
    # Every IC named in a wire or an instance is listed.
    sources = list((ROOT/'netlist').glob('*.net')) + [ROOT/'netlist/deathrace.overrides',
              ROOT/'rtl/deathrac_netlist.v', BOARD]
    netlist_v = (ROOT/'rtl/deathrac_netlist.v').read_text()
    for f in sources:
        text = f.read_text()
        refs = re.findall(rf'\b(?:n_)?({REF})_pin\d', text)
        if f.suffix in ('.net', '.overrides'):   # pins are written CHIP.PIN there
            refs += re.findall(rf'(?<![\w.])({REF})\.\d+\b', re.sub(r'#.*', '', text))
        for r in refs:
            if r not in listed: fail(errors, f'{f.name}: uses {r}, which is not in the chip list')
    for r in re.findall(rf'\bs\d\d_({REF})(?:_[a-z0-9]+)?\b', netlist_v):
        if r not in listed: fail(errors, f'deathrac_netlist.v: instance of {r}, which is not in the chip list')
    # Every listed IC is mentioned in the generated RTL (wire name, instance or comment).
    for r in listed:
        if not re.search(rf'(?<![A-Za-z0-9]){r}(?![0-9])', netlist_v):
            fail(errors, f'{r} is listed but never mentioned in rtl/deathrac_netlist.v')

def count_block(chips):
    by_type = collections.defaultdict(list)
    for r, t, note in chips:
        if r not in by_type[t]: by_type[t].append(r)
    ics = len({r for r, _, _ in chips})
    out = [COUNT_BEGIN, f'// {ics} ICs, {len(by_type)} types'
           + (' (C10 counted once per drawn type, see its note)' if any(DUPLICATE in n for *_, n in chips) else '')]
    for t, rs in sorted(by_type.items(), key=lambda x: (-len(x[1]), x[0])):
        out.append(f'// {t:<7} x{len(rs):<3} ' + ' '.join(rs))
    out.append(COUNT_END)
    return out

def main():
    checking = '--check' in sys.argv[1:]
    raw = BOARD.read_text(newline='')
    eol = '\r\n' if '\r\n' in raw else '\n'
    text = raw.replace('\r\n', '\n')
    errors = []
    chips = read_list(text, errors)
    check(chips, text, errors)
    block = '\n'.join(count_block(chips))
    try:
        head, rest = text.split(COUNT_BEGIN, 1)
        old, tail = rest.split(COUNT_END, 1)
        current = COUNT_BEGIN + old + COUNT_END
    except ValueError:
        raise SystemExit(f'ERROR: IC-type count markers not found in {BOARD}')
    stale = current != block
    for e in dict.fromkeys(errors): print('ERROR:', e)
    print(block.splitlines()[1][3:])
    if checking:
        if stale: print('ERROR: IC-type count block is stale; run python tools/ic_count.py')
        sys.exit(1 if errors or stale else 0)
    if stale:
        BOARD.write_text((head + block + tail).replace('\n', eol), newline='')
        print('updated', BOARD.relative_to(ROOT))
    sys.exit(1 if errors else 0)

if __name__ == '__main__': main()
